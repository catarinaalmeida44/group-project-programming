// The Nova lap: one lap round the Nova SBE campus in Carcavelos, the way a
// student walks it.
//
//     #  wall      .  road      ,  grass
//
// THE LAP, IN THE ORDER IT IS DRIVEN (clockwise on this map)
//   1. east along the entrance avenue, towards the glass front with the banner
//   2. through the doors and across the Hovione Atrium, the only part indoors
//   3. out of its south doors onto the terrace by the cafe
//   4. under the library and down the promenade, with the long main building
//      on the right and the Westmont Hospitality Hall on the left
//   5. down the wide stairs (driven as a ramp) to the lower plaza, in front of
//      the Grand Auditorium
//   6. west along the path past the tunnel to the beach
//   7. down a slanting path to the pavement of the coast road (the Marginal)
//   8. north up the west street, past the lawns and the academic halls
//   9. round the flags and back into the avenue
//
// HOW IT WAS MADE (17 November 2026, by Catarina with her coding agent)
// - The team filmed the lap on campus, nine minutes of walking. The agent
//   went through the film picture by picture and drew what it saw.
// - Each letter is a square of 3 by 3 metres: half the size of a square of
//   the campus loop, so everything is twice as big compared with a kart.
//   A lap along the driving line is about 730 metres.
// - It is not a survey. The real coast road runs at a slant to the buildings.
//   Here it runs straight along the bottom of the map, so that walls run
//   along the squares. The halls and lawns were placed to fit.
// - Paths were widened so that karts can pass each other: the real path past
//   the tunnel is 5 metres wide, here it is 12.
// - The stairs and the slopes are flat here: the driving rules have no hills.
//
// The letters below were not typed by hand. The ground is drawn as shapes in
// client/nova-lap-ground.js and the buildings as boxes in
// client/nova-lap-buildings.js. tests/nova-lap.test.js checks that these
// letters say the same as those shapes, square by square. To change the
// layout, change the shapes and then the letters to match.
//
// North is up: column 0 is the west edge, row 0 the north edge. The sea is
// beyond the bottom edge. The numbers after some rows are row numbers.

